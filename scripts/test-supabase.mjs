import assert from 'node:assert/strict';
import { createEditorialClient, readEditorialSettings, requireFolklyOwner } from '../server/supabase.js';
const env = { SUPABASE_URL: 'https://example.supabase.co', SUPABASE_SECRET_KEY: 'sb_secret_test' };
let options;
createEditorialClient(env, (url, key, config) => { options = config; return {}; });
assert.equal(options.auth.persistSession, false);
assert.throws(() => createEditorialClient({}), /missing/);
assert.throws(() => createEditorialClient({ ...env, SUPABASE_SECRET_KEY: 'sb_publishable_test' }), /server credential/);
assert.throws(() => createEditorialClient({ ...env, SUPABASE_URL: 'http://example.supabase.co' }), /Invalid/);
const settings = await readEditorialSettings({ from: name => { assert.equal(name, 'folkly_settings'); return { select: async () => ({ data: [{ key: 'schedule.enabled', value: 'false' }], error: null }) }; } });
assert.equal(settings['schedule.enabled'], 'false');
await assert.rejects(readEditorialSettings({ from: () => ({ select: async () => ({ error: { message: 'secret' } }) }) }), /query failed/);
assert.equal(await requireFolklyOwner(new Request('https://www.folkly.com/admin'), {}), false);
const req = new Request('https://www.folkly.com/admin', { headers: { authorization: 'Bearer fake' } });
assert.equal(await requireFolklyOwner(req, { auth: { getUser: async () => ({ error: true }) } }), false);
const client = id => ({ auth: { getUser: async () => ({ data: { user: { id: 'owner', user_metadata: { role: 'owner' } } } }) }, from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: id ? { user_id: id } : null }) }) }) }) });
assert.equal(await requireFolklyOwner(req, client(null)), false);
assert.equal(await requireFolklyOwner(req, client('other')), false);
assert.equal(await requireFolklyOwner(req, client('owner')), true);
console.log('Supabase client checks passed: server credentials, lazy setup, error handling, verified auth and private owner membership.');
