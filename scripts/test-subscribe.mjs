import assert from 'node:assert/strict';
import { createSubscribeHandler } from '../api/subscribe.js';
const saved = [];
const handler = createSubscribeHandler({ configured: () => true, save: async (path, data) => saved.push({ path, data }) });
const request = (data, origin = 'https://www.folkly.com') => new Request('https://www.folkly.com/api/subscribe', { method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: JSON.stringify(data) });
assert.equal((await handler(request({ email: ' Reader@Example.com ', consent: 'yes' }))).status, 200);
assert.equal(saved[0].data.email, 'reader@example.com');
assert.match(saved[0].path, /^subscribers\/[a-f0-9]{64}\.json$/);
assert.equal((await handler(request({ email: 'bad', consent: 'yes' }))).status, 400);
assert.equal((await handler(request({ email: 'reader@example.com' }))).status, 400);
assert.equal((await handler(request({ email: 'reader@example.com', consent: 'yes', website: 'spam' }))).status, 400);
assert.equal((await handler(request({ email: 'reader@example.com', consent: 'yes' }, 'https://other.example'))).status, 403);
assert.equal(saved.length, 1);
const unavailable = createSubscribeHandler({ configured: () => false, save: async () => assert.fail('unconfigured write') });
assert.equal((await unavailable(request({ email: 'reader@example.com', consent: 'yes' }))).status, 503);
const failure = createSubscribeHandler({ configured: () => true, save: async () => { throw new Error('private detail'); } });
const response = await failure(request({ email: 'reader@example.com', consent: 'yes' }));
assert.equal(response.status, 503);
assert(!(await response.text()).includes('private detail'));
console.log('Subscription checks passed: private record, normalized email, validation, consent, honeypot, origin check, fail-closed storage.');
